// The grove's walk obstacles are produced while the town and countryside meshes are built
// (some placements depend on the builders' seeded random streams), so shared/ cannot compute
// them without Babylon-side code. They are baked into shared/src/world/obstacles.ts instead;
// this test rebuilds them exactly as world/index.ts does and fails if the baked copy drifts.
// After changing town.ts / countryside.ts placements, regenerate the baked file with:
//   npx vitest run src/world/obstacles.test.ts -u
import { expect, it } from 'vitest';
import { GROVE_OBSTACLES } from '@sg2/shared/world/obstacles';
import { Walk, createGroveWalk, type Obstacle } from './layout';
import { Builder } from './mesh';
import { Kit } from './parts';
import { buildTown } from './town';
import { buildCountryside } from './countryside';

/** Same builders and seeds as buildWorld in index.ts (mesh colours/AO do not affect obstacles). */
function buildObstacles(): Obstacle[] {
  const town = new Kit(new Builder(11), new Builder(12));
  const props = new Kit(new Builder(13), town.g);
  const tOut = buildTown(town, props);
  const band = new Kit(new Builder(32), town.g);
  const far = new Kit(new Builder(33), new Builder(34));
  const cOut = buildCountryside(new Builder(31), band, far, new Builder(35), new Builder(36));
  return [...tOut.obstacles, ...cOut.obstacles];
}

it('baked GROVE_OBSTACLES match the obstacles the client world builds', async () => {
  const live = buildObstacles();
  expect(live.length).toBeGreaterThan(100);
  await expect([
    '// GENERATED by client/src/world/obstacles.test.ts (run it with -u) — do not edit by hand.',
    '// Every obstacle the client world builds (town, then countryside), in build order.',
    "import type { Obstacle } from './layout';",
    '',
    'export const GROVE_OBSTACLES: readonly Obstacle[] = [',
    ...live.map(o => `  ${JSON.stringify(o)},`),
    '];',
    '',
  ].join('\n')).toMatchFileSnapshot('../../../shared/src/world/obstacles.ts');
  expect(GROVE_OBSTACLES).toEqual(live);
});

it('the shared grove walk answers groundAt exactly like a Walk over the live obstacles', () => {
  const live = new Walk(buildObstacles()), shared = createGroveWalk();
  let walkable = 0;
  for (let x = -120; x <= 120; x += 0.7) for (let z = -120; z <= 120; z += 0.7) {
    const y = live.groundAt(x, z);
    if (y !== null) walkable++;
    expect(shared.groundAt(x, z)).toBe(y);
  }
  expect(walkable).toBeGreaterThan(1000);
});
