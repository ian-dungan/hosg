// Maintainer tool: turns a plain name blocklist into the hash arrays of shared/src/badwords.ts and the
// ROT13 test fixture shared/src/names.fixture.ts. The plain list is never committed.
//
// Input on stdin: one entry per line, lower-case letters. A line "[long]" starts the long entries (found
// anywhere in a name), "[short]" the short ones (refused only as a word of their own); blank lines and
// lines starting with "#" are skipped.
//
//   npx tsx shared/scripts/blocklist-hash.ts --badwords < list.txt > shared/src/badwords.ts
//   npx tsx shared/scripts/blocklist-hash.ts --fixture  < list.txt > shared/src/names.fixture.ts
//
// With neither flag, both files are printed, one after the other.
import { readFileSync } from 'node:fs';
import { BLOCKLIST_SEED, blockHash } from '../src/hash';

const collapse = (s: string) => s.replace(/(.)\1+/g, '$1');
const rot13 = (s: string) => s.replace(/[a-z]/g, (c) => String.fromCharCode(((c.charCodeAt(0) - 97 + 13) % 26) + 97));

function readList(text: string): { long: string[]; short: string[] } {
  const long: string[] = [];
  const short: string[] = [];
  let into = long;
  for (const raw of text.split('\n')) {
    const line = raw.trim().toLowerCase();
    if (line === '' || line.startsWith('#')) continue;
    if (line === '[long]') into = long;
    else if (line === '[short]') into = short;
    else if (/^[a-z]+$/.test(line)) into.push(line);
    else throw new Error(`not lower-case letters: line "${rot13(line)}" (ROT13)`);
  }
  return { long, short };
}

const unique = (xs: string[]) => [...new Set(xs)];
const wrap = (items: string[], per: number) => {
  const lines: string[] = [];
  for (let i = 0; i < items.length; i += per) lines.push('  ' + items.slice(i, i + per).join(' '));
  return lines.join('\n');
};

function badwordsSource(long: string[], short: string[]): string {
  const forms = unique(long.map(collapse));
  const hashes = unique(forms.map(blockHash)).sort();
  const lengths = unique(forms.map((f) => String(f.length))).map(Number).sort((a, b) => a - b);
  const shorts = short.map((w) => ({ h: blockHash(collapse(w)), runs: w.match(/(.)\1*/g)!.map((r) => r.length).join('') }));
  const shortKeys = unique(shorts.map((s) => `${s.h}:${s.runs}`)).sort();
  return `// Moderation blocklist for adventurer names and usernames, as hashes only: no plain-text word ships.
// Generated by shared/scripts/blocklist-hash.ts from a plain list that is never committed; edit that list
// and regenerate, never by hand. Each hash is cyrb53 (seed 0x${BLOCKLIST_SEED.toString(16)}) in base 36 of an
// entry's normalised form: lower-case letters with any letter repeated in a row written once. The tests
// try every entry through the ROT13 fixture in names.fixture.ts.

/** Long entries, searched for anywhere in a name's joined letters: one hash per normalised entry. */
export const BAD_WORD_HASHES: readonly string[] = Object.freeze([
${wrap(hashes.map((h) => `'${h}',`), 8)}
]);

/** The distinct lengths of the long entries' normalised forms: the window sizes to hash. */
export const BAD_WORD_LENGTHS: readonly number[] = Object.freeze([${lengths.join(', ')}]);

/**
 * Short entries, refused only as a word of their own (or a run of neighbouring words joined), with any
 * letter repeated more and with a plural "s" or "es": the hash of the entry's letters with repeats
 * written once, and the minimum length of each run of one letter ("12": one, then at least two).
 */
export const SHORT_BAD_HASHES: readonly { h: string; runs: string }[] = Object.freeze([
${wrap(shortKeys.map((k) => { const [h, runs] = k.split(':'); return `{ h: '${h}', runs: '${runs}' },`; }), 3)}
].map((e) => Object.freeze(e)));
`;
}

function fixtureSource(long: string[], short: string[]): string {
  const list = (xs: string[]) => wrap(xs.map((w) => `'${rot13(w)}',`), 8);
  return `// Test fixture: the name blocklist ROT13-encoded, so the tests can try every entry without the plain
// words in the source. Tests only: never import this from index.ts or from shipped code.
// Generated by shared/scripts/blocklist-hash.ts.

/** ROT13 (letters a-z only; anything else is kept). Its own inverse. */
export const rot13 = (s: string): string =>
  s.replace(/[a-z]/g, (c) => String.fromCharCode(((c.charCodeAt(0) - 97 + 13) % 26) + 97));

/** The long entries, normalised (lower-case, repeats written once), ROT13-encoded. */
export const LONG_FIXTURE: readonly string[] = [
${list(long)}
];

/** The short entries as written (lower-case letters), ROT13-encoded. */
export const SHORT_FIXTURE: readonly string[] = [
${list(short)}
];
`;
}

const { long, short } = readList(readFileSync(0, 'utf8'));
const args = process.argv.slice(2);
const out: string[] = [];
if (args.includes('--badwords') || !args.includes('--fixture')) out.push(badwordsSource(long, short));
if (args.includes('--fixture') || !args.includes('--badwords')) out.push(fixtureSource(long, short));
process.stdout.write(out.join('\n'));
process.stderr.write(`${long.length} long, ${short.length} short entries\n`);
